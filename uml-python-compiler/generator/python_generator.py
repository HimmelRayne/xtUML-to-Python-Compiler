"""Python code generator: validated AST -> Python source text."""

import keyword

TYPE_MAP = {"int": "int", "float": "float", "str": "str",
            "string": "str", "bool": "bool", "void": "None"}

INDENT = "    "


def py_type(uml_type):
    return TYPE_MAP.get(uml_type, uml_type)  # class names stay as they are


def py_name(name, visibility):
    """public -> name, private/protected -> _name"""
    return name if visibility == "public" else "_" + name


def is_many(multiplicity):
    """True if the upper bound is greater than 1 ("*", "1..*", "2..5")."""
    if multiplicity is None:
        return False
    upper = multiplicity.split("..")[-1]
    return upper == "*" or int(upper) > 1


class PythonGenerator:
    def generate(self, program):
        self.classes = {c.name: c for c in program.classes}
        self.relations = {}
        for rel in program.relationships:
            self.relations.setdefault(rel.source, []).append(rel)

        ordered = self._ordered(program.classes)
        parts = [self._class(node) for node in ordered]

        header = ["# Generated by UML Class Diagram Compiler", "from __future__ import annotations"]
        if any(self._is_abstract(c) for c in ordered):
            header.append("from abc import ABC, abstractmethod")
        return "\n".join(header) + "\n\n\n" + "\n\n\n".join(parts) + "\n"

    # ---- ordering / inheritance helpers ---------------------------
    def _ordered(self, classes):
        """Parents and interfaces must be defined before their subclasses."""
        result, seen = [], set()

        def visit(node):
            if node.name in seen:
                return
            seen.add(node.name)
            deps = ([node.parent] if node.parent else []) + node.interfaces
            for dep in deps:
                visit(self.classes[dep])
            result.append(node)

        for node in classes:
            visit(node)
        return result

    @staticmethod
    def _is_abstract(node):
        return node.kind == "interface" or node.modifier == "abstract"

    def _derives(self, name, ancestor):
        """True if class `name` inherits (directly or not) from `ancestor`."""
        node = self.classes[name]
        direct = ([node.parent] if node.parent else []) + node.interfaces
        return any(d == ancestor or self._derives(d, ancestor) for d in direct)

    def _is_abc(self, name):
        node = self.classes[name]
        direct = ([node.parent] if node.parent else []) + node.interfaces
        return self._is_abstract(node) or any(self._is_abc(d) for d in direct)

    def _all_attrs(self, node):
        """Inherited attributes first, then own (names already inherited are skipped)."""
        attrs = self._all_attrs(self.classes[node.parent]) if node.parent else []
        known = {a.name for a in attrs}
        return attrs + [a for a in node.attributes if a.name not in known]

    # ---- class ----------------------------------------------------
    def _class(self, node):
        blocks = []
        init = self._init_block(node)
        if init:
            blocks.append(init)
        blocks += [self._method_block(node, m) for m in node.methods]
        if not blocks:
            blocks = [["pass"]]

        body = "\n\n".join("\n".join(INDENT + line for line in b) for b in blocks)
        return f"class {node.name}{self._bases(node)}:\n{body}"

    def _bases(self, node):
        bases = ([node.parent] if node.parent else [])
        bases += [i for i in node.interfaces if i not in bases]
        # drop a base that another base already inherits from (avoids MRO errors)
        bases = [b for b in bases
                 if not any(o != b and self._derives(o, b) for o in bases)]
        if self._is_abstract(node) and not any(self._is_abc(b) for b in bases):
            bases.append("ABC")
        return f"({', '.join(bases)})" if bases else ""

    # ---- constructor ----------------------------------------------
    def _init_block(self, node):
        if node.kind == "interface":
            return None
        params = self._all_attrs(node)
        inherited = self._all_attrs(self.classes[node.parent]) if node.parent else []
        own = params[len(inherited):]
        fields = self.relations.get(node.name, [])
        if not own and not fields:
            return None  # nothing new: inherit the parent's __init__

        sig = ", ".join(["self"] + [f"{a.name}: {py_type(a.type)}" for a in params])
        lines = [f"def __init__({sig}):"]
        if node.parent:
            lines.append(f"{INDENT}super().__init__({', '.join(a.name for a in inherited)})")
        for a in own:
            lines.append(f"{INDENT}self.{py_name(a.name, a.visibility)} = {a.name}")

        used = {py_name(a.name, a.visibility) for a in own}
        for rel in fields:
            lines.append(INDENT + self._field(rel, used))
        return lines

    def _field(self, rel, used):
        many = is_many(rel.target_multiplicity)
        name = rel.name or (rel.target[0].lower() + rel.target[1:] + ("s" if many else ""))
        while name in used or keyword.iskeyword(name):
            name += "_"
        used.add(name)

        if many:
            code = f"self.{name}: list[{rel.target}] = []"
        else:
            code = f"self.{name}: {rel.target} | None = None"

        parts = [rel.source]
        if rel.source_multiplicity:
            parts.append(f'"{rel.source_multiplicity}"')
        parts.append("-->")
        if rel.target_multiplicity:
            parts.append(f'"{rel.target_multiplicity}"')
        parts.append(rel.target)
        return f"{code}  # association: {' '.join(parts)}"

    # ---- methods --------------------------------------------------
    def _method_block(self, node, method):
        params = ["self"] + [f"{p.name}: {py_type(p.type)}" for p in method.parameters]
        name = py_name(method.name, method.visibility)
        lines = []
        if self._is_abstract(node):
            lines.append("@abstractmethod")
        lines.append(f"def {name}({', '.join(params)}) -> {py_type(method.return_type)}:")
        lines.append(f"{INDENT}pass")
        return lines
